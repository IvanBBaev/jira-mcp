/**
 * Why a request is Cloud-only, or undefined when it is not. A Data Center
 * server answers every one of these 404, and the Data Center adapter must never
 * send one — so the fake both refuses it and records the reason.
 */
export function cloudOnlyReason(pathname, query) {
  if (pathname === '/rest/api/3' || pathname.startsWith('/rest/api/3/')) {
    return 'the Cloud platform root /rest/api/3';
  }
  if (/\/search\/(jql|approximate-count)$/.test(pathname)) {
    return 'the Cloud-only enhanced search endpoint';
  }
  if (Object.hasOwn(query, 'accountId') || Object.hasOwn(query, 'accountIds')) {
    return 'an accountId lookup (Data Center users have none)';
  }
  return undefined;
}

/**
 * Why an `Authorization` header is not the expected PAT, or undefined when it
 * is. Real Data Center also accepts HTTP Basic with a password, but the server
 * is configured for `JIRA_AUTH_MODE=pat` and must send the token as a Bearer —
 * so Basic here is the client's mistake, not a valid alternative.
 */
export function dataCenterAuthFailure(header, pat) {
  if (header === `Bearer ${pat}`) return undefined;
  if (typeof header !== 'string' || header === '') return 'no Authorization header';
  if (header.startsWith('Basic ')) return 'HTTP Basic, not a PAT bearer';
  if (!header.startsWith('Bearer ')) return 'not a Bearer token';
  return 'wrong token';
}

