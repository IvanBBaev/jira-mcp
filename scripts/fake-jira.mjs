const MEDIA_MODES = new Set(['auto', 'always', 'never']);

function assertMediaMode(mode) {
  if (!MEDIA_MODES.has(mode)) {
    throw new Error(
      `fake-jira: unknown media mode ${JSON.stringify(mode)} (auto, always or never)`,
    );
  }
}

/**
 * Start the fake.
 *
 * @param {object} options
 * @param {number} [options.port] 0 (the default) asks the OS for a free port.
 * @param {string} [options.email] The account the Basic credential must carry.
 * @param {string} [options.token] The API token the Basic credential must carry.
 * @param {string} [options.certDir] Where the TLS material lives.
 * @param {'auto'|'always'|'never'} [options.mediaMode] How
 *   `/attachment/content/{id}` answers: `auto` honours the `redirect` query
 *   parameter the way Jira Cloud documents it (so `redirect=false` returns the
 *   bytes directly), `always` forces the 303 hop, `never` forbids it.
 * @param {boolean} [options.hideWatcherRoster] Reproduce CC-47.
 * @param {boolean} [options.boardHasActiveSprint] Refuse every sprint start with
 *   the "board already has an active sprint" 400. Off by default: the fake does
 *   NOT otherwise model sprint concurrency, because the seeded board already
 *   carries an active sprint and modelling it unconditionally would make a
 *   successful start unreachable in rehearsal.
 * @param {boolean} [options.verbose] Log every request to stderr.
 * @param {'cloud'|'datacenter'} [options.deployment] Which product to stand in
 *   for. `cloud` (the default) is everything the Cloud rehearsal uses and is
 *   unchanged by the Data Center mode. `datacenter` serves only
 *   {@link DATACENTER_ROUTES}, under `contextPath`, behind a PAT Bearer, and
 *   answers every Cloud-only route 404.
 * @param {string} [options.pat] Data Center only: the personal access token
 *   the `Bearer` credential must carry.
 * @param {string} [options.contextPath] Data Center only: where the site is
 *   mounted (`/jira` by default; `''` for the host root).
 */
export async function startFakeJira(options = {}) {
  const deployment = options.deployment ?? 'cloud';
  if (deployment !== 'cloud' && deployment !== 'datacenter') {
    throw new Error(`fake-jira: unknown deployment ${JSON.stringify(deployment)}`);
  }
  // A mistyped media mode ('Always') once behaved as 'never', so the pass meant
  // to prove the 303 hop passed without taking it (CC-1503).
  assertMediaMode(options.mediaMode ?? 'auto');
  const contextPath =
    deployment === 'datacenter' ? (options.contextPath ?? DATACENTER_CONTEXT_PATH) : '';
  if (contextPath !== '' && !/^(\/[A-Za-z0-9._-]+)+$/.test(contextPath)) {
    throw new Error(`fake-jira: malformed context path ${JSON.stringify(contextPath)}`);
  }
  const config = {
    deployment,
    contextPath,
    pat: options.pat ?? DATACENTER_PAT,
    email: options.email ?? 'rehearsal@example.invalid',
    token: options.token ?? 'rehearsal-token',
    projectKey: options.projectKey ?? 'SCRATCH',
    project2Key: options.project2Key ?? 'LEGACY',
    mediaMode: options.mediaMode ?? 'auto',
    hideWatcherRoster: options.hideWatcherRoster ?? false,
    boardHasActiveSprint: options.boardHasActiveSprint ?? false,
    verbose: options.verbose ?? false,
  };
  const certDir = options.certDir ?? join(tmpdir(), 'fake-jira-tls');
  const { key, cert, certFile } = ensureCertificate(certDir);

  const server = {
    config,
    state: seedState(config),
    /** Every request, minus credential values. */
    requests: [],
    /** Queued faults, consumed in order. */
    faults: [],
    port: 0,
    origin: '',
  };
  const cloudRoutes = buildRoutes(server);
  const routes =
    deployment === 'datacenter'
      ? buildDataCenterRoutes(server, cloudRoutes)
      : cloudRoutes;

  const expectedAuth =
    'Basic ' + Buffer.from(`${config.email}:${config.token}`, 'utf8').toString('base64');

  const takeFault = (method, pathname) => {
    const index = server.faults.findIndex(
      (fault) =>
        (fault.method === undefined || fault.method === method) &&
        (fault.path === undefined || fault.path === pathname),
    );
    if (index < 0) return undefined;
    const fault = server.faults[index];
    fault.times = (fault.times ?? 1) - 1;
    if (fault.times <= 0) server.faults.splice(index, 1);
    return fault;
  };

  const httpServer = createServer({ key, cert }, (req, res) => {
    const chunks = [];
    req.on('data', (chunk) => chunks.push(chunk));
    req.on('end', () => {
      const raw = Buffer.concat(chunks);
      const url = new URL(req.url ?? '/', `https://${req.headers.host ?? API_HOST}`);
      const query = Object.fromEntries(url.searchParams.entries());
      const method = (req.method ?? 'GET').toUpperCase();
      // Data Center has no signed media host: attachments stream from the site.
      const isMediaHost =
        deployment === 'cloud' && (req.headers.host ?? '').startsWith(`${MEDIA_HOST}:`);
      // Routes are matched below the context path. A Data Center request
      // outside it would reach a different application on a real host.
      const insideContext =
        contextPath === '' || url.pathname.startsWith(`${contextPath}/`);
      const routePath = insideContext
        ? url.pathname.slice(contextPath.length)
        : url.pathname;

      const record = {
        method,
        path: url.pathname,
        query,
        host: req.headers.host,
        onMediaHost: isMediaHost,
        hasAuthorization: req.headers.authorization !== undefined,
        atlassianToken: req.headers['x-atlassian-token'],
        contentType: req.headers['content-type'],
        accept: req.headers.accept,
        bytes: raw.length,
      };
      if (deployment === 'datacenter') {
        record.authScheme = /^\S+/.exec(req.headers.authorization ?? '')?.[0];
        if (!insideContext) record.outsideContextPath = true;
        const cloudOnly = cloudOnlyReason(routePath, query);
        if (cloudOnly !== undefined) record.cloudOnly = cloudOnly;
        // The Cloud byte route, on either root (D117): Data Center serves the
        // bytes from `/secure/attachment/{id}/{filename}` only.
        if (/^\/rest\/api\/[23]\/attachment\/content(?:\/|$)/.test(routePath)) {
          record.violation = 'cloud_attachment_content_on_datacenter';
        }
      }
      server.requests.push(record);

      const send = (result) => {
        record.status = result.status;
        const headers = { ...(result.headers ?? {}) };
        let payload;
        if (result.buffer !== undefined) {
          payload = result.buffer;
          headers['content-length'] = String(payload.length);
        } else if (result.json !== undefined) {
          payload = Buffer.from(JSON.stringify(result.json), 'utf8');
          headers['content-type'] = 'application/json;charset=UTF-8';
          headers['content-length'] = String(payload.length);
        }
        if (config.verbose) {
          process.stderr.write(
            `fake-jira ${method} ${url.pathname} -> ${String(result.status)}\n`,
          );
        }
        res.writeHead(result.status, headers);
        res.end(payload);
      };

      // -- the signed media host ------------------------------------------
      if (isMediaHost) {
        const id = /^\/media\/([^/?]+)$/.exec(url.pathname)?.[1];
        const attachment =
          id === undefined ? undefined : server.state.attachments.get(id);
        if (attachment === undefined) {
          send(jiraError(404, ['Media not found.']));
          return;
        }
        // The hop must be ANONYMOUS: leaking the Jira credential to a
        // third-party media host is the exact failure `core/http.ts` guards
        // against, so the fake refuses rather than quietly accepting it.
        if (req.headers.authorization !== undefined) {
          record.violation = 'authorization_sent_to_media_host';
          send(jiraError(400, ['The media host must not receive Jira credentials.']));
          return;
        }
        send({
          status: 200,
          buffer: attachment.bytes,
          headers: { 'content-type': attachment.mimeType },
        });
        return;
      }

      const fault = takeFault(method, routePath);
      if (fault !== undefined) {
        record.faultInjected = fault.status;
        const headers = { ...(fault.headers ?? {}) };
        send({
          status: fault.status,
          json: fault.body ?? {
            errorMessages: [`Injected fault ${String(fault.status)}`],
            errors: {},
          },
          headers,
        });
        return;
      }

      if (deployment === 'datacenter') {
        const failure = dataCenterAuthFailure(req.headers.authorization, config.pat);
        if (failure !== undefined) {
          // Data Center's Seraph filter answers an unauthenticated REST call
          // with this body and names the reason in `X-Seraph-LoginReason`.
          record.authFailure = failure;
          send(
            json(
              401,
              {
                errorMessages: [
                  'You are not authenticated. Authentication required to perform this operation.',
                ],
                errors: {},
              },
              {
                'x-seraph-loginreason': 'AUTHENTICATED_FAILED',
                'www-authenticate': 'Bearer realm="Jira"',
              },
            ),
          );
          return;
        }
      } else if (req.headers.authorization !== expectedAuth) {
        // Jira Cloud basic auth is `email:apiToken`, in that order. A client
        // that swapped them, or that sent a Bearer token, would authenticate
        // against nothing on a real site and get this same 401 — but the
        // recorded reason makes the rehearsal say WHY instead of leaving the
        // operator to guess.
        const parsed = parseBasicAuth(req.headers.authorization);
        record.authFailure =
          parsed === undefined
            ? 'not HTTP Basic'
            : parsed.user === config.token
              ? 'email and token are the wrong way round'
              : parsed.user !== config.email
                ? 'unexpected username'
                : 'wrong token';
        send(
          json(
            401,
            {
              errorMessages: ['Client must be authenticated to access this resource.'],
              errors: {},
            },
            { 'www-authenticate': 'Basic realm="Jira"' },
          ),
        );
        return;
      }

      let body;
      if (raw.length > 0 && (req.headers['content-type'] ?? '').includes('json')) {
        try {
          body = JSON.parse(raw.toString('utf8'));
        } catch {
          send(jiraError(400, ['The request body could not be parsed as JSON.']));
          return;
        }
      }
      record.body = body;

      // Data Center has none of the Cloud-only surface. Refused before routing
      // so a Cloud route that happens to share a path can never answer it.
      if (record.cloudOnly !== undefined || record.outsideContextPath === true) {
        record.unmatched = true;
        send(jiraError(404, [`Data Center has no ${method} ${url.pathname}`]));
        return;
      }

      for (const [routeMethod, pattern, handler] of routes) {
        if (routeMethod !== method) continue;
        const params = matchPath(pattern, routePath);
        if (params === undefined) continue;
        record.route = `${routeMethod} ${pattern}`;
        try {
          send(
            handler({ params, query, body, raw, headers: req.headers, method, record }),
          );
        } catch (error) {
          record.handlerError = String(error);
          send(jiraError(500, [`fake-jira handler crashed: ${String(error)}`]));
        }
        return;
      }

      // Nothing matched. Recorded loudly, because an unmatched route in a
      // rehearsal means the fake is missing an endpoint the client really uses.
      record.unmatched = true;
      send(jiraError(404, [`fake-jira has no route for ${method} ${url.pathname}`]));
    });
  });

  await new Promise((resolve, reject) => {
    httpServer.once('error', reject);
    httpServer.listen(options.port ?? 0, '127.0.0.1', resolve);
  });
  server.port = httpServer.address().port;
  // The origin is what the client's JIRA_SITE is set to, so under Data Center
  // it carries the context path — which is also the base every `self` link
  // and attachment URL the fake emits is built on, as on a real host.
  server.origin = `https://${API_HOST}:${String(server.port)}${contextPath}`;

  return {
    port: server.port,
    origin: server.origin,
    certFile,
    state: server.state,
    requests: server.requests,
    config,
    /** Queue faults to be returned by the next matching requests. */
    arm(...faults) {
      server.faults.push(...faults);
    },
    /** Forget the recorded traffic — handy between rehearsal passes. */
    clearRequests() {
      server.requests.length = 0;
    },
    setMediaMode(mode) {
      assertMediaMode(mode);
      config.mediaMode = mode;
    },
    async close() {
      await new Promise((resolve) => httpServer.close(resolve));
    },
  };
}

