/**
 * Written into a rehearsal's workdir and injected with `--import` (through the
 * child's NODE_OPTIONS only) so that it applies to `verify-live.mjs` AND to the
 * server it spawns. Shared by scripts/rehearse-live.mjs (Cloud) and
 * scripts/rehearse-datacenter.mjs (Data Center), so both reach the fake
 * through one and the same patch. Undici (Node's fetch) resolves
 * through `dns.lookup`, so patching it is enough; nothing else about the request
 * changes — the SNI, the Host header and the certificate check all still say
 * `jira.rehearsal.test`, which is exactly the point. If the server ever grew a
 * second network path that bypassed `dns.lookup`, this rehearsal would start
 * failing rather than silently passing.
 */
export const REHEARSAL_DNS_PRELOAD = `// Generated by scripts/fake-jira.mjs. Child-process only.
import dns from 'node:dns';

const HOSTS = new Set(${JSON.stringify([API_HOST, MEDIA_HOST])});
const ADDRESS = '127.0.0.1';
const FAMILY = 4;

const realLookup = dns.lookup;
dns.lookup = function lookup(hostname, options, callback) {
  if (!HOSTS.has(hostname)) return realLookup.call(this, hostname, options, callback);
  const done = typeof options === 'function' ? options : callback;
  const opts =
    typeof options === 'function'
      ? {}
      : typeof options === 'number'
        ? { family: options }
        : (options ?? {});
  queueMicrotask(() => {
    if (opts.all === true) done(null, [{ address: ADDRESS, family: FAMILY }]);
    else done(null, ADDRESS, FAMILY);
  });
  return undefined;
};

const realPromised = dns.promises.lookup;
dns.promises.lookup = async function lookup(hostname, options) {
  if (!HOSTS.has(hostname)) return realPromised.call(this, hostname, options);
  const opts = typeof options === 'number' ? { family: options } : (options ?? {});
  return opts.all === true
    ? [{ address: ADDRESS, family: FAMILY }]
    : { address: ADDRESS, family: FAMILY };
};
`;

