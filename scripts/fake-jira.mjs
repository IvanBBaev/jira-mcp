/** A list query parameter or body property, as an array of strings. */
function listOf(value) {
  if (value === undefined || value === null) return undefined;
  if (Array.isArray(value)) return value.map(String);
  return String(value).split(',');
}

/**
 * The Data Center route table, in the same `[method, path, handler]` form as
 * {@link buildRoutes}. Paths are relative to the context path. The two agile
 * list routes carry no user and no rich text, so they reuse the Cloud handlers
 * as they are; everything else is projected here.
 */
function buildDataCenterRoutes(server, cloudRoutes) {
  const { state } = server;
  const base = () => server.origin;
  const findIssue = (wanted) => {
    const byKey = state.issues.get(wanted);
    if (byKey !== undefined && !byKey.deleted) return byKey;
    for (const issue of state.issues.values()) {
      if (issue.id === wanted && !issue.deleted) return issue;
    }
    return undefined;
  };
  const findProject = (wanted) =>
    state.projects.find((project) => project.key === wanted || project.id === wanted);
  const cloud = (method, path) =>
    cloudRoutes.find(([m, p]) => m === method && p === path)[2];
  /**
   * A Data Center `values` page (the create metadata, D116): `startAt` /
   * `maxResults` / `total` / `isLast` beside the rows.
   */
  const paged = (rows, query) => {
    const startAt = Number(query.startAt ?? 0);
    const maxResults = Math.min(Number(query.maxResults ?? 50), 1000);
    return {
      startAt,
      maxResults,
      total: rows.length,
      isLast: startAt + maxResults >= rows.length,
      values: rows.slice(startAt, startAt + maxResults),
    };
  };
  /** Classic page over an array: `startAt` / `maxResults` / `total`. */
  const classic = (rows, query, key) => {
    const startAt = Number(query.startAt ?? 0);
    const maxResults = Math.min(Number(query.maxResults ?? 50), 1000);
    return {
      startAt,
      maxResults,
      total: rows.length,
      [key]: rows.slice(startAt, startAt + maxResults),
    };
  };

  const routes = [
    // The legacy all-projects create metadata. Jira 9.0 removed it, and the
    // adapter must never call it (D116): it answers 404 as a 9.x host does
    // (the path then falls to the issue route) and is recorded as a violation.
    // Listed first so `/issue/{issueIdOrKey}` cannot swallow it, and kept out
    // of DATACENTER_ROUTES, which lists what a clean rehearsal must hit.
    [
      'GET',
      '/rest/api/2/issue/createmeta',
      (ctx) => {
        ctx.record.violation = 'legacy_createmeta_removed_in_jira_9';
        return notFound('Issue');
      },
    ],

    [
      'GET',
      '/rest/api/2/myself',
      () => {
        const self = state.users[0];
        return json(200, {
          ...dcUser(state, self.accountId, base()),
          locale: self.locale,
          groups: { size: 1, items: [] },
          applicationRoles: { size: 1, items: [] },
          expand: 'groups,applicationRoles',
        });
      },
    ],
    [
      'GET',
      '/rest/api/2/mypermissions',
      (ctx) => {
        // D122. Data Center answers every permission it knows whether or not
        // a `permissions` filter was sent (older builds ignore it), in the same
        // record shape as Cloud; the api ring keeps only what it asked for
        // (CC-1402). An unknown scope is a 404 here too.
        const projectRef = ctx.query.projectKey ?? ctx.query.projectId;
        if (projectRef !== undefined && findProject(projectRef) === undefined) {
          return notFound('Project');
        }
        const issueRef = ctx.query.issueKey ?? ctx.query.issueId;
        if (issueRef !== undefined && findIssue(issueRef) === undefined) {
          return notFound('Issue');
        }
        return json(200, {
          permissions: Object.fromEntries(
            Object.keys(PERMISSION_CATALOG).map((key) => [key, permissionRecord(key)]),
          ),
        });
      },
    ],

    [
      'POST',
      '/rest/api/2/search',
      (ctx) => {
        const body = ctx.body ?? {};
        // A Cloud-shaped body on the classic endpoint: Data Center does not
        // know `nextPageToken`, and a client that sent one would page wrongly.
        if (Object.hasOwn(body, 'nextPageToken')) {
          ctx.record.violation = 'cloud_cursor_on_classic_search';
          return jiraError(400, ['Unrecognized field "nextPageToken".']);
        }
        const projectKey = projectFromJql(body.jql);
        const rows = [...state.issues.values()]
          .filter((issue) => !issue.deleted)
          .filter((issue) => projectKey === undefined || issue.projectKey === projectKey)
          .sort((left, right) => left.created.localeCompare(right.created));
        const startAt = Number(body.startAt ?? 0);
        const maxResults = Math.min(Number(body.maxResults ?? 50), 1000);
        const fields = listOf(body.fields);
        const expand = listOf(body.expand);
        return json(200, {
          expand: 'schema,names',
          startAt,
          maxResults,
          total: rows.length,
          issues: rows
            .slice(startAt, startAt + maxResults)
            .map((issue) => dcIssue(state, issue, base(), { fields, expand })),
        });
      },
    ],

    [
      'GET',
      '/rest/api/2/issue/{issueIdOrKey}',
      (ctx) => {
        const issue = findIssue(ctx.params.issueIdOrKey);
        if (issue === undefined) return notFound('Issue');
        return json(
          200,
          dcIssue(state, issue, base(), {
            fields: listOf(ctx.query.fields),
            expand: listOf(ctx.query.expand),
          }),
        );
      },
    ],

    [
      'GET',
      '/rest/api/2/issue/{issueIdOrKey}/comment',
      (ctx) => {
        const issue = findIssue(ctx.params.issueIdOrKey);
        if (issue === undefined) return notFound('Issue');
        const rows = issue.comments.map((comment) =>
          dcComment(state, issue, comment, base()),
        );
        return json(200, classic(rows, ctx.query, 'comments'));
      },
    ],

    [
      'GET',
      '/rest/api/2/issue/{issueIdOrKey}/worklog',
      (ctx) => {
        const issue = findIssue(ctx.params.issueIdOrKey);
        if (issue === undefined) return notFound('Issue');
        const rows = issue.worklogs.map((worklog) =>
          dcWorklog(state, issue, worklog, base()),
        );
        return json(200, classic(rows, ctx.query, 'worklogs'));
      },
    ],

    [
      'GET',
      '/rest/api/2/issue/{issueIdOrKey}/transitions',
      (ctx) => {
        if (findIssue(ctx.params.issueIdOrKey) === undefined) return notFound('Issue');
        return json(200, wireTransitions());
      },
    ],

    [
      'GET',
      '/rest/api/2/issue/{issueIdOrKey}/watchers',
      (ctx) => {
        const issue = findIssue(ctx.params.issueIdOrKey);
        if (issue === undefined) return notFound('Issue');
        return json(200, {
          self: `${base()}/rest/api/2/issue/${issue.key}/watchers`,
          isWatching: issue.watchers.includes(state.users[0].accountId),
          watchCount: issue.watchers.length,
          watchers: issue.watchers.map((accountId) => dcUser(state, accountId, base())),
        });
      },
    ],

    [
      'GET',
      '/rest/api/2/project',
      (ctx) =>
        json(
          200,
          state.projects.map((project) =>
            dcProject(state, project, base(), ctx.query.expand, false),
          ),
        ),
    ],

    [
      'GET',
      '/rest/api/2/project/{projectIdOrKey}',
      (ctx) => {
        const project = findProject(ctx.params.projectIdOrKey);
        if (project === undefined) return notFound('Project');
        return json(200, dcProject(state, project, base(), ctx.query.expand, true));
      },
    ],

    [
      'GET',
      '/rest/api/2/project/{projectIdOrKey}/components',
      (ctx) => {
        const project = findProject(ctx.params.projectIdOrKey);
        if (project === undefined) return notFound('Project');
        return json(
          200,
          [...state.components.values()]
            .filter((component) => component.projectKey === project.key)
            .map((component) => dcComponent(state, component, base(), project.id)),
        );
      },
    ],

    [
      'GET',
      '/rest/api/2/project/{projectIdOrKey}/versions',
      (ctx) => {
        const project = findProject(ctx.params.projectIdOrKey);
        if (project === undefined) return notFound('Project');
        return json(
          200,
          [...state.versions.values()]
            .filter((version) => String(version.projectId) === project.id)
            .map((version) => dcVersion(version, base())),
        );
      },
    ],

    [
      'GET',
      '/rest/api/2/field',
      () =>
        json(
          200,
          wireFields().map((field) => {
            // No `key` / `untranslatedName` on Data Center, and a description
            // is a plain string field, not an ADF document.
            const rest = { ...field };
            delete rest.key;
            delete rest.untranslatedName;
            return field.id === 'description'
              ? { ...rest, schema: { type: 'string', system: 'description' } }
              : rest;
          }),
        ),
    ],

    [
      'GET',
      '/rest/api/2/status',
      () => {
        const category = (id, key, name, colorName) => ({
          self: `${base()}/rest/api/2/statuscategory/${String(id)}`,
          id,
          key,
          colorName,
          name,
        });
        return json(200, [
          {
            self: `${base()}/rest/api/2/status/1`,
            description: '',
            name: 'To Do',
            id: '1',
            statusCategory: category(2, 'new', 'To Do', 'blue-gray'),
          },
          {
            self: `${base()}/rest/api/2/status/3`,
            description: 'This issue is being actively worked on.',
            name: 'In Progress',
            id: '3',
            statusCategory: category(4, 'indeterminate', 'In Progress', 'yellow'),
          },
          {
            self: `${base()}/rest/api/2/status/10001`,
            description: '',
            name: 'Done',
            id: '10001',
            statusCategory: category(3, 'done', 'Done', 'green'),
          },
        ]);
      },
    ],

    [
      'GET',
      '/rest/api/2/issueLinkType',
      () =>
        json(200, {
          issueLinkTypes: LINK_TYPES.map((type) => ({
            ...type,
            self: `${base()}/rest/api/2/issueLinkType/${type.id}`,
          })),
        }),
    ],

    ['GET', '/rest/agile/1.0/board', cloud('GET', '/rest/agile/1.0/board')],

    [
      'GET',
      '/rest/agile/1.0/board/{boardId}/sprint',
      cloud('GET', '/rest/agile/1.0/board/{boardId}/sprint'),
    ],

    [
      'GET',
      '/rest/agile/1.0/sprint/{sprintId}/issue',
      (ctx) => {
        const sprintId = Number(ctx.params.sprintId);
        if (!state.sprints.some((sprint) => sprint.id === sprintId)) {
          return notFound('Sprint');
        }
        const fields = listOf(ctx.query.fields);
        const rows = [...state.issues.values()]
          .filter((issue) => !issue.deleted && issue.sprintId === sprintId)
          .map((issue) => dcIssue(state, issue, base(), { fields }));
        return json(200, {
          expand: 'schema,names',
          ...classic(rows, ctx.query, 'issues'),
        });
      },
    ],

    // -- users and project roles (D110) ------------------------------------
    [
      'GET',
      '/rest/api/2/user/search',
      (ctx) => {
        const refused = userLookupRefusal(ctx);
        if (refused !== undefined) return refused;
        return json(200, userWindow(ctx.query));
      },
    ],

    [
      'GET',
      '/rest/api/2/user/assignable/search',
      (ctx) => {
        const refused = userLookupRefusal(ctx);
        if (refused !== undefined) return refused;
        const { project, issueKey } = ctx.query;
        if (issueKey !== undefined) {
          if (findIssue(String(issueKey)) === undefined) return notFound('Issue');
        } else if (project !== undefined) {
          if (findProject(String(project)) === undefined) return notFound('Project');
        } else {
          return jiraError(400, [
            'Either the project key or the issue key must be supplied.',
          ]);
        }
        return json(200, userWindow(ctx.query));
      },
    ],

    [
      'GET',
      '/rest/api/2/project/{projectIdOrKey}/role',
      (ctx) => {
        const project = findProject(ctx.params.projectIdOrKey);
        if (project === undefined) return notFound('Project');
        return json(200, {
          Administrators: `${base()}/rest/api/2/project/${project.key}/role/10002`,
          Developers: `${base()}/rest/api/2/project/${project.key}/role/10001`,
        });
      },
    ],

    [
      'GET',
      '/rest/api/2/project/{projectIdOrKey}/role/{roleId}',
      (ctx) => {
        const project = findProject(ctx.params.projectIdOrKey);
        if (project === undefined) return notFound('Project');
        const names = { 10001: 'Developers', 10002: 'Administrators' };
        const name = names[ctx.params.roleId];
        if (name === undefined) return notFound('Project role');
        const self = state.users[0];
        // Data Center role actors: no `actorUser`, no accountId — a user actor
        // is named by `name`, and both kinds carry an avatar URL the server's
        // allowlist has to drop.
        return json(200, {
          self: `${base()}/rest/api/2/project/${project.key}/role/${ctx.params.roleId}`,
          name,
          id: Number(ctx.params.roleId),
          description: `A project role that represents ${name.toLowerCase()}.`,
          actors: [
            {
              id: 10240,
              displayName: self.displayName,
              type: 'atlassian-user-role-actor',
              name: self.name,
              avatarUrl: `${base()}/secure/useravatar?size=xsmall&ownerId=${encodeURIComponent(self.name)}`,
            },
            {
              id: 10241,
              displayName: 'jira-administrators',
              type: 'atlassian-group-role-actor',
              name: 'jira-administrators',
              avatarUrl: `${base()}/secure/useravatar?size=xsmall&avatarId=10123`,
            },
          ],
        });
      },
    ],

    // -- saved filters (D115) ------------------------------------------------
    // Cloud's `/filter/search` is not a route the Data Center adapter may
    // rely on: it is answered 404 and recorded as a violation, so a Data Center
    // client that reached for it fails the rehearsal instead of passing on a
    // route a real host may not have. Listed before `/filter/{id}`, which
    // would otherwise take `search` for an id.
    [
      'GET',
      '/rest/api/2/filter/search',
      (ctx) => {
        ctx.record.violation = 'cloud_filter_search_on_datacenter';
        return jiraError(404, ['Data Center has no GET /rest/api/2/filter/search']);
      },
    ],
    [
      'GET',
      '/rest/api/2/filter/favourite',
      () =>
        json(
          200,
          state.filters
            .filter((filter) => filter.favourite === true)
            .map((filter) => dcFilter(state, filter, base())),
        ),
    ],
    [
      'GET',
      '/rest/api/2/filter/{id}',
      (ctx) => {
        const filter = state.filters.find((row) => row.id === ctx.params.id);
        if (filter === undefined) return notFound('Filter');
        return json(200, dcFilter(state, filter, base()));
      },
    ],

    // -- attachment download (D117) -----------------------------------------
    // Data Center has no `/attachment/content/{id}`: a client that reaches for
    // it (on either root) is recorded as a violation. Listed before
    // `/attachment/{id}`, which would otherwise take `content` for an id.
    [
      'GET',
      '/rest/api/2/attachment/content/{id}',
      (ctx) => {
        ctx.record.violation = 'cloud_attachment_content_on_datacenter';
        return jiraError(404, ['Data Center has no GET /rest/api/2/attachment/content']);
      },
    ],
    [
      'GET',
      '/rest/api/2/attachment/{id}',
      (ctx) => {
        const attachment = state.attachments.get(ctx.params.id);
        if (attachment === undefined) return notFound('Attachment');
        return json(200, dcAttachment(state, attachment, base()));
      },
    ],
    // The attachment servlet: outside the REST API, under the context path,
    // behind the same PAT. The name segment must be the attachment's filename
    // — the documented URL carries it — so a request for another name is a
    // 404, as a client that guessed or followed something else would get.
    [
      'GET',
      '/secure/attachment/{id}/{filename}',
      (ctx) => {
        const attachment = state.attachments.get(ctx.params.id);
        if (attachment === undefined || attachment.filename !== ctx.params.filename) {
          return notFound('Attachment');
        }
        return {
          status: 200,
          buffer: attachment.bytes,
          headers: { 'content-type': attachment.mimeType },
        };
      },
    ],

    // -- create metadata (D116) ---------------------------------------------
    [
      'GET',
      '/rest/api/2/issue/createmeta/{projectIdOrKey}/issuetypes',
      (ctx) => {
        const project = findProject(ctx.params.projectIdOrKey);
        if (project === undefined) return notFound('Project');
        const rows = DATACENTER_CREATE_META_ISSUE_TYPES.map((row) => ({
          self: `${base()}/rest/api/2/issuetype/${row.id}`,
          ...row,
          iconUrl: `${base()}/secure/viewavatar?size=xsmall&avatarId=10318&avatarType=issuetype`,
        }));
        return json(200, paged(rows, ctx.query));
      },
    ],

    [
      'GET',
      '/rest/api/2/issue/createmeta/{projectIdOrKey}/issuetypes/{issueTypeId}',
      (ctx) => {
        const project = findProject(ctx.params.projectIdOrKey);
        if (project === undefined) return notFound('Project');
        const known = DATACENTER_CREATE_META_ISSUE_TYPES.some(
          (row) => row.id === ctx.params.issueTypeId,
        );
        if (!known) return notFound('Issue type');
        return json(
          200,
          paged(dcCreateMetaFields(state, base(), project.key), ctx.query),
        );
      },
    ],
  ];

  /**
   * The Data Center user lookup takes `username` and nothing else: `query` is
   * the Cloud parameter (a DC server ignores it and then complains that
   * `username` is missing), and an `accountId` is refused as Cloud-only
   * before any route runs (`cloudOnlyReason`).
   */
  function userLookupRefusal(ctx) {
    if (Object.hasOwn(ctx.query, 'query')) {
      ctx.record.violation = 'cloud_query_param_on_user_search';
      return jiraError(400, ['The username query parameter was not provided']);
    }
    if (typeof ctx.query.username !== 'string' || ctx.query.username === '') {
      return jiraError(400, ['The username query parameter was not provided']);
    }
    return undefined;
  }

  /** Users matching `username` by name, display name or email, as a bare array. */
  function userWindow(query) {
    const wanted = String(query.username).toLowerCase();
    const startAt = Number(query.startAt ?? 0);
    const maxResults = Math.min(Number(query.maxResults ?? 50), 1000);
    return state.users
      .filter(
        (user) =>
          user.name.toLowerCase().includes(wanted) ||
          user.displayName.toLowerCase().includes(wanted) ||
          (user.emailAddress ?? '').toLowerCase().includes(wanted),
      )
      .slice(startAt, startAt + maxResults)
      .map((user) => dcUser(state, user.accountId, base()));
  }

  return routes;
}

