/**
 * `argv[1]` and this module, compared through realpath: Node realpaths the
 * entry module, so a symlinked checkout (macOS `/tmp` is one) or a path with
 * spaces would otherwise fail the guard and exit 0 having done nothing (CC-217).
 */
function isEntryPoint(moduleUrl) {
  const entry = process.argv[1];
  if (entry === undefined || entry === '') return false;
  const real = (path) => {
    try {
      return realpathSync(path);
    } catch {
      return path;
    }
  };
  return real(resolve(entry)) === real(fileURLToPath(moduleUrl));
}

const invokedDirectly = isEntryPoint(import.meta.url);

if (invokedDirectly) {
  const { values } = parseArgs({
    args: process.argv.slice(2),
    options: {
      port: { type: 'string', default: '0' },
      email: { type: 'string' },
      token: { type: 'string' },
      'cert-dir': { type: 'string' },
      media: { type: 'string', default: 'auto' },
      quiet: { type: 'boolean', default: false },
      deployment: { type: 'string', default: 'cloud' },
      pat: { type: 'string' },
      'context-path': { type: 'string' },
    },
    strict: true,
  });
  const fake = await startFakeJira({
    port: Number(values.port),
    email: values.email,
    token: values.token,
    certDir: values['cert-dir'],
    mediaMode: values.media,
    verbose: values.quiet !== true,
    deployment: values.deployment,
    pat: values.pat,
    contextPath: values['context-path'],
  });
  const dataCenter = fake.config.deployment === 'datacenter';
  process.stderr.write(
    [
      `fake-jira (${fake.config.deployment}) listening on ${fake.origin} (bound to 127.0.0.1:${String(fake.port)})`,
      `  JIRA_SITE=${fake.origin}`,
      ...(dataCenter
        ? [
            `  JIRA_ALLOWED_HOSTS=${API_HOST}`,
            '  JIRA_DEPLOYMENT=datacenter JIRA_DATACENTER_PREVIEW=true JIRA_AUTH_MODE=pat',
            `  JIRA_PAT=${fake.config.pat}`,
          ]
        : [`  JIRA_ALLOWED_HOSTS=${API_HOST},${MEDIA_HOST}`]),
      `  NODE_EXTRA_CA_CERTS=${fake.certFile}`,
      `  ${dataCenter ? API_HOST : `${API_HOST} and ${MEDIA_HOST}`} must resolve to 127.0.0.1 for the client`,
      '',
    ].join('\n'),
  );
}
