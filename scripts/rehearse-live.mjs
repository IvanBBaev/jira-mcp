/**
 * Invariants that hold in every pass, however the fake is configured. These are
 * the ones worth failing loudly: a route the fake does not implement means the
 * rehearsal silently skipped part of the wire, and a credential on the media
 * host is a real leak — Atlassian's media domain is a different origin, and the
 * whole point of the 303 hop is that the second request is unauthenticated.
 */
function universalChecks({ requests }) {
  const failures = [];
  const unmatched = requests.filter((r) => r.unmatched === true);
  if (unmatched.length > 0) {
    const names = [...new Set(unmatched.map((r) => `${r.method} ${r.path}`))];
    failures.push(`fake has no route for: ${names.join(', ')}`);
  }
  const leaked = requests.filter((r) => r.onMediaHost && r.hasAuthorization);
  if (leaked.length > 0) {
    failures.push(`credentials sent to the media host ${String(leaked.length)}x`);
  }
  const violations = requests.filter((r) => r.violation !== undefined);
  if (violations.length > 0) {
    failures.push(
      `fake flagged: ${[...new Set(violations.map((r) => r.violation))].join(', ')}`,
    );
  }
  const unauthenticated = requests.filter((r) => r.authFailure !== undefined);
  if (unauthenticated.length > 0) {
    failures.push(
      `the client failed authentication: ${[
        ...new Set(unauthenticated.map((r) => r.authFailure)),
      ].join(', ')}`,
    );
  }
  const broke = requests.filter((r) => r.handlerError !== undefined);
  if (broke.length > 0) {
    failures.push(
      `fake handler threw on ${broke.length} request(s): ${broke[0].handlerError}`,
    );
  }
  return failures;
}

/**
 * The agile write surface, asserted from the wire and from the fake's state
 * rather than only from the driver's own verdicts.
 *
 * A claim that says PASS proves the driver was satisfied; these checks prove
 * what actually reached the fake. The distinction matters most for the two
 * details a live tenant will judge us on: `originBoardId` must go out as a
 * NUMBER, and the sprint lifecycle must be driven with POST (partial update),
 * never PUT — Jira's PUT nulls every field the body omits, which would silently
 * wipe a real sprint's goal and dates.
 */
function agileWriteChecks({ requests, claims, state }) {
  const failures = [];
  const agile = (method, re) =>
    requests.filter((r) => r.method === method && re.test(r.path));

  const creates = agile('POST', /^\/rest\/agile\/1\.0\/sprint$/);
  if (creates.length !== 1) {
    failures.push(`expected exactly 1 POST /agile/sprint, saw ${String(creates.length)}`);
  } else {
    const create = creates[0];
    if (create.status !== 201) {
      failures.push(`sprint create answered ${String(create.status)}, expected 201`);
    }
    if (typeof create.body?.originBoardId !== 'number') {
      failures.push(
        `originBoardId went on the wire as ${typeof create.body?.originBoardId}, ` +
          'expected a number (the agile twin of the POST /version projectId trap)',
      );
    }
  }

  if (agile('POST', /^\/rest\/agile\/1\.0\/sprint\/\d+\/issue$/).length === 0) {
    failures.push('no issue was moved into a sprint');
  }
  if (agile('POST', /^\/rest\/agile\/1\.0\/backlog\/issue$/).length === 0) {
    failures.push('no issue was moved back to the backlog');
  }

  const lifecycle = agile('POST', /^\/rest\/agile\/1\.0\/sprint\/\d+$/);
  const states = lifecycle.map((r) => r.body?.state);
  if (!states.includes('active')) failures.push('the sprint was never started');
  if (!states.includes('closed')) failures.push('the sprint was never closed');
  if (agile('PUT', /^\/rest\/agile\/1\.0\/sprint\//).length > 0) {
    failures.push(
      'a sprint update used PUT — Jira PUT is a FULL update and nulls omitted fields',
    );
  }

  // The fake's own view: the sprint the driver made really is closed, and it is
  // still there, because nothing can delete it.
  const created = state.sprints.filter((sprint) => /^gate-c-/.test(sprint.name));
  if (created.length !== 1) {
    failures.push(`expected 1 gate-c sprint on the fake, saw ${String(created.length)}`);
  } else if (created[0].state !== 'closed') {
    failures.push(`the gate-c sprint ended in state ${String(created[0].state)}`);
  }

  for (const id of ['C27', 'C28', 'C29', 'C30']) {
    const row = claims.find((c) => c.id === id);
    if (row === undefined) failures.push(`${id} did not run`);
    else if (row.status !== 'PASS') failures.push(`${id} is ${row.status}: ${row.note}`);
  }
  // C27's note is the only place a reader is told the sprint is permanent.
  const c27 = claims.find((c) => c.id === 'C27');
  if (c27 !== undefined && !/DELETE A SPRINT/.test(c27.note)) {
    failures.push('C27 stopped saying that the sprint it creates cannot be deleted');
  }
  return failures;
}

/**
 * The residue tail, which every invocation now runs (C32).
 *
 * The inventory is the operator's only honest answer to "what did that just
 * leave on my site", so a pass that stops producing it is a regression even when
 * every other claim is green.
 */
function residueChecks({ claims, stderr }, expected = {}) {
  const failures = [];
  const c32 = claims.find((c) => c.id === 'C32');
  if (c32 === undefined) failures.push('C32 did not run — the run left no inventory');
  else if (c32.status !== 'PASS') failures.push(`C32 is ${c32.status}: ${c32.note}`);
  else {
    for (const [kind, count] of Object.entries(expected)) {
      if (!new RegExp(`\\b${kind}=${String(count)}\\b`).test(c32.note)) {
        failures.push(`C32 should report ${kind}=${String(count)}, said: ${c32.note}`);
      }
    }
  }
  // The inventory is printed on stderr, where diagnostics belong — stdout is
  // the claim report. Both halves matter: an operator reads the rendering, and
  // an empty class has to say so rather than vanish.
  if (!stderr.includes('Residue — what this gate can still see on the site')) {
    failures.push('the residue table was never rendered');
  }
  for (const title of [
    'throwaway issues',
    'project versions',
    'project components',
    'sprints',
    'local files in JIRA_MEDIA_DIR',
  ]) {
    if (!stderr.includes(title)) failures.push(`the residue table omits "${title}"`);
  }
  return failures;
}

/** Every agile write claim SKIPped, with nothing having reached the wire. */
function agileWriteSkipped(claims, why) {
  const failures = [];
  for (const id of ['C27', 'C28', 'C29', 'C30']) {
    const row = claims.find((c) => c.id === id);
    if (row === undefined) failures.push(`${id} did not run`);
    else if (row.status !== 'SKIP') {
      failures.push(`${id} should SKIP ${why}, got ${row.status}: ${row.note}`);
    }
  }
  return failures;
}

