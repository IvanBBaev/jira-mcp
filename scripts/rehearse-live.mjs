async function main() {
  const { values } = parseArgs({
    args: process.argv.slice(2),
    options: {
      pass: { type: 'string', multiple: true },
      dump: { type: 'boolean', default: false },
      keep: { type: 'boolean', default: false },
      verbose: { type: 'boolean', default: false },
      help: { type: 'boolean', default: false },
    },
    strict: true,
  });

  if (values.help === true) {
    process.stdout.write(
      'rehearse-live — run scripts/verify-live.mjs against scripts/fake-jira.mjs.\n\n' +
        'Flags: --pass <A..K> (repeatable), --dump, --keep, --verbose, --help\n',
    );
    return EXIT_OK;
  }

  if (!existsSync(SERVER_ENTRY)) {
    process.stderr.write(`no build at ${SERVER_ENTRY} — run \`npm run build\` first.\n`);
    return EXIT_CONFIG;
  }

  const selected =
    values.pass === undefined
      ? PASSES
      : PASSES.filter((pass) => values.pass.includes(pass.id));
  if (selected.length === 0) {
    process.stderr.write(`no pass matched ${String(values.pass)}\n`);
    return EXIT_CONFIG;
  }

  const workdir = await mkdtemp(join(tmpdir(), 'rehearse-live-'));
  const certDir = join(workdir, 'tls');
  const preload = join(workdir, 'rehearsal-dns.mjs');
  await mkdir(certDir, { recursive: true });
  await writeFile(preload, PRELOAD_SOURCE, 'utf8');

  const context = {
    workdir,
    certDir,
    preloadUrl: pathToFileURL(preload).href,
    verbose: values.verbose === true,
    dump: values.dump === true,
  };

  const results = [];
  try {
    for (const pass of selected) {
      process.stdout.write(`\n=== pass ${pass.id}: ${pass.title}\n`);
      const result = await runPass(pass, context);
      if (result.recordDir !== undefined) {
        result.failures.push(
          ...(await auditRecording(result.recordDir, result.accountIds)),
        );
      }
      results.push(result);
      report(result);
    }
  } finally {
    if (values.keep === true) {
      process.stdout.write(`\nworkdir kept: ${workdir}\n`);
    } else {
      await rm(workdir, { recursive: true, force: true });
    }
  }

  return summarise(results);
}

function report(result) {
  const counts = { PASS: 0, FAIL: 0, SKIP: 0 };
  for (const claim of result.claims) counts[claim.status] += 1;
  process.stdout.write(
    `    ${String(counts.PASS)} passed, ${String(counts.FAIL)} failed, ` +
      `${String(counts.SKIP)} skipped, exit ${String(result.exitCode)}\n`,
  );
  for (const claim of result.claims) {
    if (claim.status === 'PASS') continue;
    process.stdout.write(
      `    ${claim.status}  ${claim.id}  ${claim.title}` +
        (claim.note === '' ? '' : `  — ${claim.note}`) +
        '\n',
    );
  }
  for (const failure of result.failures) {
    process.stdout.write(`    REHEARSAL FAILURE  ${failure}\n`);
  }
  if (result.dump === true) {
    for (const request of result.requests) {
      const query = new URLSearchParams(request.query).toString();
      process.stdout.write(
        `    ${String(request.status ?? '---')} ${request.method} ${request.path}` +
          `${query === '' ? '' : `?${query}`}` +
          `${request.onMediaHost ? '  [media host]' : ''}` +
          `${request.hasAuthorization ? '' : '  [no auth]'}\n`,
      );
    }
  }
}

function summarise(results) {
  process.stdout.write('\n=== rehearsal summary\n');
  let bad = 0;
  for (const result of results) {
    const ok = result.failures.length === 0;
    if (!ok) bad += 1;
    process.stdout.write(
      `  ${ok ? 'ok  ' : 'BAD '} pass ${result.pass.id}  ${result.pass.title}\n`,
    );
  }
  if (bad === 0) {
    process.stdout.write(
      '\nThe driver behaved. This says nothing about whether Jira agrees —\n' +
        'see docs/RELEASING.md §6 for what still needs a real tenant.\n',
    );
    return EXIT_OK;
  }
  process.stdout.write(`\n${String(bad)} pass(es) regressed.\n`);
  return EXIT_FAILURE;
}

main()
  .then((code) => {
    process.exitCode = code;
  })
  .catch((error) => {
    process.stderr.write(`rehearse-live failed: ${String(error?.stack ?? error)}\n`);
    process.exitCode = EXIT_CONFIG;
  });
