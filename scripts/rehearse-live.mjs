#!/usr/bin/env node
/**
 * rehearse-live — run the Gate C driver end to end against a fake Jira.
 *
 * Gate C is expensive: the owner has to provision a scratch Jira Cloud site,
 * seed it, and babysit a run. Every bug in `scripts/verify-live.mjs` that only
 * shows up on the wire costs one of those round trips. This script makes the
 * first live run boring by running the *whole* driver — the same
 * `verify-live.mjs`, spawning the same `build/index.js`, over the same stdio
 * transport — against `scripts/fake-jira.mjs` instead of Atlassian.
 *
 * WHAT THIS PROVES, AND WHAT IT DOES NOT. It proves things about the DRIVER and
 * about the SERVER'S PLUMBING: that every claim's tool arguments satisfy the
 * tool schemas, that the claims sequence correctly, that the write gate behaves,
 * that paging terminates, that a 429 is retried and an unsafe write is not, that
 * no credential reaches the media host, that the report and exit codes are what
 * the runbook says. It proves NOTHING about Jira. Where the fake had to take a
 * position on a wire detail that only Atlassian can settle, `fake-jira.mjs` says
 * so at the route and `docs/RELEASING.md` §6 lists it as still needing Gate C. A
 * green rehearsal is a statement about our code, never about theirs.
 *
 * HOW IT REACHES THE FAKE WITHOUT WEAKENING ANYTHING. The server refuses
 * loopback by construction: `core/http.ts` applies the SSRF blocklist BEFORE the
 * allowlist, so `127.0.0.1`, `*.localhost`, `*.local` and `*.internal` are
 * unreachable no matter what `JIRA_ALLOWED_HOSTS` says — as they should be.
 * Rather than punch a hole in that, the fake answers to two ordinary DNS names,
 * `jira.rehearsal.test` and `media.rehearsal.test`, which are neither blocked
 * nor canonical, and which reach the fake only because:
 *
 *   - they are allowlisted through the supported `JIRA_ALLOWED_HOSTS` path;
 *   - `dns.lookup` is patched to `127.0.0.1` for exactly those two names,
 *     inside the spawned child only, via a `--import` preload;
 *   - the fake's self-signed cert is trusted through `NODE_EXTRA_CA_CERTS`.
 *
 * No source file changes, no test-only branch in `src/`, no relaxed host rule.
 * A build with the blocklist removed would still fail this rehearsal's
 * assertions the same way — the DNS patch is scoped to the child process and
 * cannot be reached from a normal run.
 *
 * Usage:
 *   node scripts/rehearse-live.mjs             # every pass
 *   node scripts/rehearse-live.mjs --pass A    # one pass
 *   node scripts/rehearse-live.mjs --keep      # keep the workdir for forensics
 *   node scripts/rehearse-live.mjs --verbose   # stream the driver's own output
 *
 * Exit codes: 0 = every pass met its expectations, 1 = something regressed,
 * 2 = setup error (no build, no openssl).
 */

